const fiberPkg = "github.com/gofiber/fiber/v2"
const httpxPkg = "github.com/Abraxas-365/iamkit/internal/httpx"

// Response is one documented answer of an operation. Schema nil means a
// body that is not JSON-typed (raw bytes, HTML, a redirect).
type Response struct {
	Status      int // 0 = status chosen at run time (documented as default)
	ContentType string
	Schema      map[string]any
}

// Operation is what the analyser learned about one handler.
type Operation struct {
	Summary     string
	Body        map[string]any // JSON request body
	Form        []string       // form fields (FormValue)
	Query       map[string]string
	Responses   []Response
	Open        bool // the handler answers through code the analyser cannot follow
	Unresolved  bool // the handler itself was not found
	ContentType string
}

// Analyzer reads handler source with go/types.
type Analyzer struct {
	pkgs     []*packages.Package
	funcs    map[string]*funcSource // "pkg.Func" / "pkg.(*T).M" → declaration
	lits     map[string]*funcSource // "file:line" → literal
	byObj    map[types.Object]*funcSource
	schemas  *schemas
	fiberCtx types.Type
}

type funcSource struct {
	pkg  *packages.Package
	decl *ast.FuncDecl
	lit  *ast.FuncLit
	doc  string
}

func (f *funcSource) params() *ast.FieldList {
	if f.decl != nil {
		return f.decl.Type.Params
	}
	return f.lit.Type.Params
}

func (f *funcSource) body() *ast.BlockStmt {
	if f.decl != nil {
		return f.decl.Body
	}
	return f.lit.Body
}

// Load parses and type-checks the module's internal packages from dir.
func Load(dir string) (*Analyzer, error) {
	cfg := &packages.Config{Dir: dir, Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo | packages.NeedImports | packages.NeedDeps}
	pkgs, err := packages.Load(cfg, "./internal/...")
	if err != nil {
		return nil, err
	}
	a := &Analyzer{pkgs: pkgs, funcs: map[string]*funcSource{}, lits: map[string]*funcSource{}, byObj: map[types.Object]*funcSource{}, schemas: newSchemas()}
	for _, p := range pkgs {
		if len(p.Errors) > 0 {
			return nil, p.Errors[0]
		}
		for _, file := range p.Syntax {
			for _, d := range file.Decls {
				fn, ok := d.(*ast.FuncDecl)
				if !ok || fn.Body == nil {
					continue
				}
				src := &funcSource{pkg: p, decl: fn, doc: fn.Doc.Text()}
				a.funcs[declName(p.PkgPath, fn)] = src
				if obj := p.TypesInfo.Defs[fn.Name]; obj != nil {
					a.byObj[obj] = src
				}
				doc := fn.Doc.Text()
				ast.Inspect(fn.Body, func(n ast.Node) bool {
					if lit, ok := n.(*ast.FuncLit); ok {
						pos := p.Fset.Position(lit.Pos())
						key := filepath.Clean(pos.Filename) + ":" + itoa(pos.Line)
						if _, seen := a.lits[key]; !seen {
							a.lits[key] = &funcSource{pkg: p, lit: lit, doc: doc}
						}
					}
					return true
				})
			}
		}
		if p.PkgPath == "github.com/Abraxas-365/iamkit/internal/server" {
			for _, imp := range p.Types.Imports() {
				if imp.Path() == fiberPkg {
					a.fiberCtx = types.NewPointer(imp.Scope().Lookup("Ctx").Type())
				}
			}
		}
	}
	return a, nil
}

func itoa(n int) string { return constant.MakeInt64(int64(n)).ExactString() }

func declName(pkg string, fn *ast.FuncDecl) string {
	if fn.Recv == nil || len(fn.Recv.List) == 0 {
		return pkg + "." + fn.Name.Name
	}
	t := fn.Recv.List[0].Type
	star := false
	if s, ok := t.(*ast.StarExpr); ok {
		t, star = s.X, true
	}
	if idx, ok := t.(*ast.IndexExpr); ok {
		t = idx.X
	}
	name := t.(*ast.Ident).Name
	if star {
		return pkg + ".(*" + name + ")." + fn.Name.Name
	}
	return pkg + "." + name + "." + fn.Name.Name
}

// Find locates a handler from its runtime name and source position.
func (a *Analyzer) Find(name, file string, line int) *funcSource {
	if strings.Contains(name, ".func") || strings.HasSuffix(name, "-fm") && file != "<autogenerated>" {
		if src, ok := a.lits[filepath.Clean(file)+":"+itoa(line)]; ok {
			return src
		}
	}
	return a.funcs[strings.TrimSuffix(name, "-fm")]
}

// Analyze inspects one handler.
func (a *Analyzer) Analyze(src *funcSource) Operation {
	op := Operation{Query: map[string]string{}}
	if src == nil {
		op.Unresolved, op.Open = true, true
		return op
	}
	op.Summary = summary(src.doc)
	ctx := a.ctxParam(src)
	if ctx == nil {
		op.Open = true
		return op
	}
	w := &walker{a: a, op: &op, seen: map[*funcSource]bool{}}
	w.function(src, ctx, frame{}, 0)
	return op
}

func summary(doc string) string {
	doc = strings.TrimSpace(strings.Join(strings.Fields(doc), " "))
	if doc == "" {
		return ""
	}
	if i := strings.Index(doc, ". "); i > 0 {
		doc = doc[:i+1]
	}
	if len(doc) > 200 {
		doc = doc[:197] + "..."
	}
	return doc
}

func (a *Analyzer) ctxParam(src *funcSource) *types.Var {
	for _, field := range src.params().List {
		for _, name := range field.Names {
			if v, ok := src.pkg.TypesInfo.Defs[name].(*types.Var); ok && a.isCtx(v.Type()) {
				return v
			}
		}
	}
	return nil
}

func (a *Analyzer) isCtx(t types.Type) bool {
	p, ok := t.(*types.Pointer)
	if !ok {
		return false
	}
	n, ok := p.Elem().(*types.Named)
	return ok && n.Obj().Name() == "Ctx" && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == fiberPkg
}

// unknownType marks a raw body whose Content-Type the analyser cannot tell.
const unknownType = "?"

type walker struct {
	a    *Analyzer
	op   *Operation
	seen map[*funcSource]bool
	// contentType is the last Content-Type the handler set (raw sends).
	contentType string
}

// frame carries what a call site knows about a helper's parameters: integer
// constants (status codes) and functions passed as values (issue callbacks).
type frame struct {
	consts map[*types.Var]constant.Value
	fns    map[*types.Var]*funcSource
}

// function walks src where ctx is the request.
func (w *walker) function(src *funcSource, ctx *types.Var, consts frame, depth int) {
	if w.seen[src] || depth > 5 {
		return
	}
	w.seen[src] = true
	defer delete(w.seen, src)
	// A Content-Type set in a helper applies to its own sends only.
	defer func(ct string) { w.contentType = ct }(w.contentType)
	info := src.pkg.TypesInfo
	ast.Inspect(src.body(), func(n ast.Node) bool {
		switch x := n.(type) {
		case *ast.FuncLit:
			return true
		case *ast.ReturnStmt:
			for _, r := range x.Results {
				if call, ok := ast.Unparen(r).(*ast.CallExpr); ok && w.passesCtx(info, call, ctx) && w.callee(info, call, consts) == nil && !w.ctxMethod(info, call, ctx) {
					w.op.Open = true
				}
			}
		case *ast.CallExpr:
			w.call(src, info, x, ctx, consts, depth)
		}
		return true
	})
}

func (w *walker) isCtxExpr(info *types.Info, e ast.Expr, ctx *types.Var) bool {
	id, ok := ast.Unparen(e).(*ast.Ident)
	return ok && info.Uses[id] == ctx
}

func (w *walker) ctxMethod(info *types.Info, call *ast.CallExpr, ctx *types.Var) bool {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	if w.isCtxExpr(info, sel.X, ctx) {
		return true
	}
	if inner, ok := sel.X.(*ast.CallExpr); ok {
		return w.ctxMethod(info, inner, ctx)
	}
	return false
}

func (w *walker) passesCtx(info *types.Info, call *ast.CallExpr, ctx *types.Var) bool {
	for _, arg := range call.Args {
		if w.isCtxExpr(info, arg, ctx) {
			return true
		}
	}
	return false
}

func (w *walker) callee(info *types.Info, call *ast.CallExpr, f frame) *funcSource {
	if id, ok := call.Fun.(*ast.Ident); ok {
		if v, ok := info.Uses[id].(*types.Var); ok {
			return f.fns[v]
		}
	}
	if sel, ok := call.Fun.(*ast.SelectorExpr); ok {
		if s, ok := info.Selections[sel]; ok && s.Kind() == types.FieldVal {
			return w.a.funcs[Bindings[fieldName(s)]]
		}
	}
	return w.function_(info, call.Fun)
}

