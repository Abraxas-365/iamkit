export type AccountTranslate = (key: string, ...args: string[]) => string;

/** Looks a key up: caller texts › English. */
export function accountTranslator(texts?: Record<string, string>): AccountTranslate {
  return (key, ...args) => {
    let s = texts?.[key] ?? accountTexts[key] ?? key;
    for (const a of args) s = s.replace("%s", a);
    return s;
  };
}
